-- Private PostgreSQL schema, accessed directly by Python rather than the Data API.
CREATE SCHEMA IF NOT EXISTS fitness;
REVOKE ALL ON SCHEMA fitness FROM PUBLIC;

CREATE TABLE IF NOT EXISTS fitness.activities (
    source TEXT NOT NULL,
    source_id TEXT NOT NULL,
    source_app TEXT,
    exercise_type_code INTEGER NOT NULL,
    start_utc TIMESTAMPTZ NOT NULL,
    end_utc TIMESTAMPTZ NOT NULL,
    tz_offset_s INTEGER NOT NULL,
    duration_s DOUBLE PRECISION NOT NULL CHECK (duration_s >= 0),
    distance_m DOUBLE PRECISION CHECK (distance_m >= 0),
    last_modified_utc TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (source, source_id)
);
CREATE INDEX IF NOT EXISTS activities_start ON fitness.activities(start_utc);

CREATE TABLE IF NOT EXISTS fitness.ingest_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at TIMESTAMPTZ NOT NULL,
    completed_at TIMESTAMPTZ,
    file_id_or_name TEXT NOT NULL,
    checksum TEXT NOT NULL,
    source_version TEXT,
    rows_seen INTEGER NOT NULL DEFAULT 0,
    rows_new INTEGER NOT NULL DEFAULT 0,
    rows_updated INTEGER NOT NULL DEFAULT 0,
    status TEXT NOT NULL,
    error TEXT
);
CREATE INDEX IF NOT EXISTS ingest_checksum ON fitness.ingest_runs(checksum, status);
REVOKE ALL ON ALL TABLES IN SCHEMA fitness FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA fitness FROM PUBLIC;
